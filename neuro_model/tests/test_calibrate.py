"""
The bounded grid search of ``neuro_model.calibrate`` (D36), without a database.

What is asserted is what the command relies on: the search never leaves the
admissible region, it is deterministic, it prefers parameters that explain the
data, and it recovers the generating parameters on data large enough to
identify them.
"""

from __future__ import annotations

import math
import random

import pytest

from neuro_model import bkt, calibrate

G_MAX, S_MAX = 0.30, 0.10
SEED = 20261003


def simulate(*, p0: float, pt: float, g0: float, s0: float, learners: int, length: int) -> list[list[bool]]:
    """Answer sequences generated by the model itself, with a fixed seed."""
    rng = random.Random(SEED)
    sequences = []
    for _ in range(learners):
        p_l = p0
        sequence = []
        for _ in range(length):
            p_hat = bkt.predict(p_l=p_l, guess=g0, slip=s0)
            is_correct = rng.random() < p_hat
            sequence.append(is_correct)
            p_l = bkt.step(p_l=p_l, guess=g0, slip=s0, pt=pt, is_correct=is_correct).p_after
        sequences.append(sequence)
    return sequences


def test_no_data_has_nothing_to_fit():
    assert calibrate.grid_search([], g_max=G_MAX, s_max=S_MAX) is None
    assert calibrate.grid_search([[], []], g_max=G_MAX, s_max=S_MAX) is None


def test_the_fit_stays_inside_the_bounds():
    sequences = simulate(p0=0.3, pt=0.15, g0=0.2, s0=0.05, learners=20, length=8)
    best = calibrate.grid_search(sequences, g_max=G_MAX, s_max=S_MAX)
    assert best is not None
    assert 0.0 < best.p0 < 1.0
    assert 0.0 <= best.pt <= 1.0
    assert 0.0 < best.g0 < G_MAX
    assert 0.0 < best.s0 < S_MAX


def test_tighter_bounds_are_respected():
    sequences = simulate(p0=0.3, pt=0.15, g0=0.2, s0=0.05, learners=20, length=8)
    best = calibrate.grid_search(sequences, g_max=0.12, s_max=0.04)
    assert best is not None
    assert best.g0 < 0.12
    assert best.s0 < 0.04


def test_bounds_that_admit_nothing_return_none():
    sequences = simulate(p0=0.3, pt=0.15, g0=0.2, s0=0.05, learners=5, length=5)
    assert calibrate.grid_search(sequences, g_max=0.001, s_max=0.001) is None


def test_the_search_is_deterministic():
    sequences = simulate(p0=0.3, pt=0.15, g0=0.2, s0=0.05, learners=10, length=6)
    first = calibrate.grid_search(sequences, g_max=G_MAX, s_max=S_MAX)
    second = calibrate.grid_search(sequences, g_max=G_MAX, s_max=S_MAX)
    assert first == second


def test_the_fit_beats_an_implausible_parameter_set():
    sequences = simulate(p0=0.3, pt=0.15, g0=0.2, s0=0.05, learners=30, length=10)
    best = calibrate.grid_search(sequences, g_max=G_MAX, s_max=S_MAX)
    assert best is not None
    worse = calibrate.log_likelihood(sequences, p0=0.05, pt=0.05, g0=0.05, s0=0.09)
    assert best.log_likelihood > worse


def test_all_correct_answers_pull_the_prior_up():
    sequences = [[True] * 10 for _ in range(20)]
    best = calibrate.grid_search(sequences, g_max=G_MAX, s_max=S_MAX)
    assert best is not None
    assert best.p0 >= 0.4


def test_all_wrong_answers_pull_the_prior_down():
    sequences = [[False] * 10 for _ in range(20)]
    best = calibrate.grid_search(sequences, g_max=G_MAX, s_max=S_MAX)
    assert best is not None
    assert best.p0 <= 0.10


def test_the_generating_parameters_are_recovered_closely():
    """On enough data the fit lands on the grid point next to the truth."""
    truth = dict(p0=0.30, pt=0.15, g0=0.20, s0=0.05)
    sequences = simulate(**truth, learners=120, length=12)
    best = calibrate.grid_search(sequences, g_max=G_MAX, s_max=S_MAX)
    assert best is not None
    assert best.p0 == pytest.approx(truth["p0"], abs=0.15)
    assert best.g0 == pytest.approx(truth["g0"], abs=0.10)
    assert best.s0 == pytest.approx(truth["s0"], abs=0.05)
    # And it is at least as likely as the truth itself on this sample.
    assert best.log_likelihood >= calibrate.log_likelihood(sequences, **truth) - 1e-9


def test_the_likelihood_is_finite_even_for_impossible_answers():
    """The floor keeps one surprising answer from collapsing the whole fit."""
    value = calibrate.log_likelihood([[False]], p0=0.999999, pt=0.0, g0=0.299999, s0=0.000001)
    assert math.isfinite(value)


def test_count_observations():
    assert calibrate.count_observations([[True, False], [True]]) == 3
    assert calibrate.count_observations([]) == 0


def test_the_candidate_list_is_sorted_and_bounded():
    candidates = calibrate.DEFAULT_GRID.candidates(g_max=G_MAX, s_max=S_MAX)
    assert candidates == sorted(candidates)
    assert all(g0 < G_MAX and s0 < S_MAX for _, _, g0, s0 in candidates)
    assert len(candidates) == len(set(candidates))


